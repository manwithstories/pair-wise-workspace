#!/usr/bin/env python3
"""Generate deterministic subtitle fixtures using only glyphs in synth.ttf."""
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]
CORPUS = (
    "中文字幕测试避头尾英运行时动态排版预检量包围盒省略号换位置零宽断非法节样式分段批处理溢出条目形度余末孤立全角标点硬优先贪心算规划最小化并稳定摘要同输入低内存可复现九语种混合组附加符第一二保持级的是在不了有和人这大为上个国我以他来用们生到作地于就对成会主发年工也能下过子说产面而方后多学所民得经十三之进着等部家电力里如水高自起物实都两体制机当使从业本去把性好应开它还因由其些然前外天政四日那社义事平相表"
)

PHRASES = [
    "中文字幕", "运行时排版", "动态测量", "预检包围盒", "省略号换行", "零宽断行",
    "非法字节", "样式分段", "批处理溢出", "条目位置", "测试避头尾", "英文混排",
    "字形度量", "行尾余量", "末行孤立", "换行位置", "运行时预检", "字幕包围盒",
    "动态字幕", "九语种", "全角标点", "硬换行优先", "贪心算法", "动态规划",
    "最小化余量", "并行处理", "稳定摘要", "同输入同输出", "低内存", "可复现",
]
LATIN = ["runtime", "subtitle", "layout", "overflow", "glyph", "kerning",
         "raggedness", "QA", "CJK", "mixed", "line-break", "ellipsis"]


def make_text(rng: random.Random, index: int, target: int) -> str:
    if index == 31:
        return "Supercalifragilisticexpialidocious" * 2 + " long unbreakable token"
    if index == 57:
        return "missing glyph 😀 must be reported once."
    if index == 78:
        return "零宽\u200b断行" + "、".join(["动态字幕"] * 8) + "，非法\\xff字节。"
    if index == 99:
        return "第一段硬换行\\n第二段保持优先级，NBSP\u00a0不换行，non\u2011breaking。"
    parts = []
    size = 0
    while size < target:
        if rng.random() < 0.22:
            token = " " + rng.choice(LATIN) + " "
        else:
            token = rng.choice(PHRASES)
            if rng.random() < 0.4:
                token += rng.choice("、。，；")
        parts.append(token)
        size += max(1, len(token))
    text = "".join(parts)
    if index % 17 == 0:
        text += " 组合e\u0301附加符。"
    return text


def cue_block(index: int, text: str) -> str:
    style = "emphasis" if index % 9 == 0 else "default"
    segment = ["opening", "runtime", "qa"][index % 3]
    return f"[cue c{index:04d} style={style} segment={segment}]\n{text}\n\n"


def main() -> None:
    rng = random.Random(7)
    cues = []
    for i in range(120):
        target = 35 + rng.randrange(35)
        cues.append(make_text(rng, i, target))
    header = (
        "# deterministic smx fixture; generated by scripts/gen_fixtures.py\n"
        "STYLE default family=SMXSynth size=32\n"
        "[style emphasis weight=bold]\n"
        "[segment opening]\n\n"
    )
    used = {c for text in cues for c in text if '\u4e00' <= c <= '\u9fff'}
    missing = sorted(used - set(CORPUS))
    if missing:
        raise SystemExit("fixture uses glyphs absent from synth font: " + "".join(missing))
    body = header + "".join(cue_block(i + 1, text) for i, text in enumerate(cues))
    (ROOT / "fixtures").mkdir(parents=True, exist_ok=True)
    (ROOT / "fixtures" / "cues.txt").write_text(body, encoding="utf-8", newline="\n")
    cue_dir = ROOT / "fixtures" / "cues"
    cue_dir.mkdir(parents=True, exist_ok=True)
    for part in range(3):
        name = cue_dir / f"part-{part + 1}.txt"
        blocks = "".join(cue_block(i + 1, cues[i]) for i in range(part * 40, part * 40 + 40))
        name.write_text(header + blocks, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
