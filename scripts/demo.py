#!/usr/bin/env python3
"""End-to-end demonstration for the block-FFT reverb CLI.

Generates a reproducible underground-ruins style scene (pulse + footsteps +
stereo ambience convolved with a long-tail impulse response), drives the
real command-line entry point in-process, and prints where every artifact
landed. All data is generated by ``src.signal_gen`` — no external files.

Run from the repository root:

    python scripts/demo.py
"""
from __future__ import annotations

import sys
from pathlib import Path

# Make ``src`` importable when the script is launched directly (no install).
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.reverb_cli import main  # noqa: E402


def run() -> int:
    artifacts = ROOT / "artifacts" / "demo_result.json"
    argv = [
        "render",
        "--duration", "1.25",
        "--sample-rate", "48000",
        "--channels", "2",
        "--block-size", "1024",
        "--ir-length", "12000",
        "--seed", "7",
        "--json-output", str(artifacts),
    ]
    print("== reverb CLI demo ==")
    print("invoking:", "python -m src.reverb_cli", " ".join(argv[1:]))
    print("-" * 60)
    code = main(argv)
    print("-" * 60)
    if code == 0:
        print(f"artifacts directory: {artifacts.parent}")
        for path in sorted(artifacts.parent.glob("demo_*")):
            print(f"  {path.name}  ({path.stat().st_size:,} bytes)")
        print("demo finished successfully (exit code 0)")
    else:
        print(f"demo failed with exit code {code}")
    return code


if __name__ == "__main__":
    raise SystemExit(run())
