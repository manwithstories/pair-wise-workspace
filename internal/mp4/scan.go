// Package mp4 performs bounds-checked ISO-BMFF / CMAF box parsing and
// deterministic fragment (de)serialization. It rejects out-of-bounds lengths
// and truncated boxes and reports the byte offset of the first fault.
package mp4

import (
	"encoding/binary"
	"math"

	"mediad/internal/core"
)

