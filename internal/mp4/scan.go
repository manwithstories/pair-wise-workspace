// BoxHeader describes one parsed box header.
type BoxHeader struct {
	Type       string // four-codes, kept as string for map/key readability
	Offset     int64  // absolute offset of the box size field
	Size       int64  // total box size including header
	HeaderSize int    // 8 or 16
	PayloadOff int64  // absolute offset of first payload byte
	End        int64  // absolute offset one past the box
}

// ReadHeader parses a single box header starting at off in data. Every failure
// is a *core.Fault carrying the first offending offset.
func ReadHeader(data []byte, off int64) (BoxHeader, error) {
	if off < 0 || off > int64(len(data)) {
		return BoxHeader{}, core.Faultf(core.KindOutOfBounds, off, "header offset outside buffer of %d bytes", len(data))
	}
	remain := int64(len(data)) - off
	if remain < 8 {
		return BoxHeader{}, core.Faultf(core.KindTruncated, off, "need 8 bytes for box header, have %d", remain)
	}
	size32 := binary.BigEndian.Uint32(data[off : off+4])
	h := BoxHeader{
		Type:       string(data[off+4 : off+8]),
		Offset:     off,
		HeaderSize: 8,
	}

	switch {
	case size32 == 1: // 64-bit largesize
		if remain < 16 {
			return BoxHeader{}, core.Faultf(core.KindTruncated, off, "box %q largesize header needs 16 bytes, have %d", h.Type, remain)
		}
		large := binary.BigEndian.Uint64(data[off+8 : off+16])
		if large < 16 {
			return BoxHeader{}, core.Faultf(core.KindBoxLength, off, "box %q largesize %d shorter than 16-byte header", h.Type, large)
		}
		if large > uint64(math.MaxInt64) {
			return BoxHeader{}, core.Faultf(core.KindOutOfBounds, off, "box %q largesize %d overflows int64", h.Type, large)
		}
		h.Size = int64(large)
		h.HeaderSize = 16
	case size32 == 0: // box extends to end of resource
		h.Size = remain
	default:
		if size32 < 8 {
			return BoxHeader{}, core.Faultf(core.KindBoxLength, off, "box %q declared size %d shorter than 8-byte header", h.Type, size32)
		}
		h.Size = int64(size32)
	}

	h.PayloadOff = off + int64(h.HeaderSize)
	end, ok := core.AddChecked(off, h.Size)
	if !ok || end < off {
		return BoxHeader{}, core.Faultf(core.KindOutOfBounds, off, "box %q end offset overflows", h.Type)
	}
	if end > int64(len(data)) {
		return BoxHeader{}, core.Faultf(core.KindTruncated, off, "box %q declares %d bytes but only %d remain", h.Type, h.Size, remain)
	}
	h.End = end
	return h, nil
}

// WalkTop visits every top-level box in data in order. The callback may return
// a fault to stop iteration; that error is returned unchanged.
func WalkTop(data []byte, fn func(BoxHeader) error) error {
	var off int64
	for off < int64(len(data)) {
		h, err := ReadHeader(data, off)
		if err != nil {
			return err
		}
		if err := fn(h); err != nil {
			return err
		}
		if h.Size == 0 {
			return nil
		}
		off = h.End
	}
	return nil
}

// FindDirectChild locates the first direct child box of parent whose type
// matches. A child whose declared range escapes the parent is rejected.
func FindDirectChild(data []byte, parent BoxHeader, typ string) (BoxHeader, bool, error) {
	off := parent.PayloadOff
	for off < parent.End {
		h, err := ReadHeader(data, off)
		if err != nil {
			return BoxHeader{}, false, err
		}
		if h.End > parent.End {
			return BoxHeader{}, false, core.Faultf(core.KindOutOfBounds, off,
				"child %q end %d exceeds parent %q end %d", h.Type, h.End, parent.Type, parent.End)
		}
		if h.Type == typ {
			return h, true, nil
		}
		off = h.End
	}
	return BoxHeader{}, false, nil
}

// FindPath follows a chain of direct children (for example moof/traf/tfdt).
func FindPath(data []byte, root BoxHeader, types ...string) (BoxHeader, bool, error) {
	cur := root
	for _, typ := range types {
		next, ok, err := FindDirectChild(data, cur, typ)
		if err != nil {
			return BoxHeader{}, false, err
		}
		if !ok {
			return BoxHeader{}, false, nil
		}
		cur = next
	}
	return cur, true, nil
}

// ReadFullBox reads version and flags of a FullBox at its payload offset.
func ReadFullBox(data []byte, h BoxHeader) (version byte, flags uint32, payload int64, err error) {
	if h.End-h.PayloadOff < 4 {
		return 0, 0, 0, core.Faultf(core.KindTruncated, h.Offset, "box %q missing full-box version/flags", h.Type)
	}
	b := data[h.PayloadOff : h.PayloadOff+4]
	version = b[0]
	flags = uint32(b[1])<<16 | uint32(b[2])<<8 | uint32(b[3])
	return version, flags, h.PayloadOff + 4, nil
}
