// Package codec 实现 8x8 DCT 变换、量化与块级编解码。
package codec

import "math"

// dctCos[u][x] = 0.5 * alpha(u) * cos((2x+1)uπ/16)，构成正交变换矩阵。
var dctCos [8][8]float64

func init() {
	for u := 0; u < 8; u++ {
		alpha := 1.0
		if u == 0 {
			alpha = 1 / math.Sqrt2
		}
		for x := 0; x < 8; x++ {
			dctCos[u][x] = 0.5 * alpha * math.Cos((2*float64(x)+1)*float64(u)*math.Pi/16)
		}
	}
}

// fdct8x8 计算正变换：out = C · in · Cᵀ。
func fdct8x8(in, out *[64]float64) {
	var tmp [64]float64
	for u := 0; u < 8; u++ {
		for y := 0; y < 8; y++ {
			s := 0.0
			for x := 0; x < 8; x++ {
				s += dctCos[u][x] * in[y*8+x]
			}
			tmp[y*8+u] = s
		}
	}
	for v := 0; v < 8; v++ {
		for u := 0; u < 8; u++ {
			s := 0.0
			for y := 0; y < 8; y++ {
				s += dctCos[v][y] * tmp[y*8+u]
			}
			out[v*8+u] = s
		}
	}
}

// idct8x8 计算逆变换：out = Cᵀ · in · C。
func idct8x8(in, out *[64]float64) {
	var tmp [64]float64
	for x := 0; x < 8; x++ {
		for v := 0; v < 8; v++ {
			s := 0.0
			for u := 0; u < 8; u++ {
				s += dctCos[u][x] * in[v*8+u]
			}
			tmp[v*8+x] = s
		}
	}
	for y := 0; y < 8; y++ {
		for x := 0; x < 8; x++ {
			s := 0.0
			for v := 0; v < 8; v++ {
				s += dctCos[v][y] * tmp[v*8+x]
			}
			out[y*8+x] = s
		}
	}
}

