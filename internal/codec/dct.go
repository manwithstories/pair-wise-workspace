// qscale 把 QP(0.25..51，0.25 步进) 映射为量化步长倍率。
// 使用 1.5 次幂曲线：低 QP 精细、高 QP 压缩能力强，且全程平滑，
// 让 R=A·Q^-B 幂律模型在全区间都有较好的拟合度。
func qscale(qp float64) float64 {
	if qp < 0.25 {
		qp = 0.25
	}
	if qp > 51 {
		qp = 51
	}
	return math.Pow(qp/8.0, 1.5)
}
