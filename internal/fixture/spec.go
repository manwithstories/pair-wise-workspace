// Package fixture generates all local test media: deterministic MP4/MXF
// containers, fault variants (truncated tables, illegal crop) and RTP
// packet streams with duplicates, reordering, sequence wraparound and
// burst loss. No external files are ever referenced.
package fixture

import (
	"crypto/sha256"
	"encoding/binary"
)

// Packet flags carried inside the 12-byte RTP payload header.
const (
	FlagFirst = 1 << 0
	FlagLast  = 1 << 1
	FlagKey   = 1 << 2
)

// PayloadHeaderSize is the custom header prepended to every RTP payload.
// Layout: uint32 sampleIndex, uint32 sampleOffset, uint16 sampleSize,
// uint16 flags. The remaining bytes are deterministic sample content.
const PayloadHeaderSize = 14

// Spec describes one generated media asset and its transport behaviour.
type Spec struct {
	Seed         int64
	SampleCount  int
	Width        uint32
	Height       uint32
	Timescale    uint32 // track edit rate numerator, denominator 1
	FrameDelta   uint32 // ticks per sample
	KeyEvery     int    // key frame period in samples
	Codec        string // e.g. "avc1"; "unknown" simulates unsupported codec
	Rotation     int    // degrees, right angle only
	// MP4 faults.
	TruncateSTSZ bool // rewrite stsz with a reduced entry count
	TruncateMDAT bool // truncate the file inside sample data
	IllegalCrop  bool // emit a clap box outside the coded frame
	BadTimeBase  bool // emit a zero timescale
	// Colour descriptions (nil = absent).
	TrackColour     *[3]uint16
	ContainerColour *[3]uint16
	// Transport faults applied when packetising.
	DropBurstAt int // first sequence number of a burst loss (-1 = none)
	DropBurstN  int
	DuplicateN  int // number of duplicated packets
	ReorderWin  int // window size for out-of-order delivery
}

// DefaultSpec returns the deterministic ~1000-sample video spec used by
// the acceptance demo.
func DefaultSpec(seed int64) Spec {
	return Spec{
		Seed: seed, SampleCount: 1000, Width: 1920, Height: 1080,
		Timescale: 24000, FrameDelta: 1001, KeyEvery: 24,
		Codec: "avc1",
		DropBurstAt: -1,
	}
}

// SampleSize returns the deterministic coded size of one sample. Sizes
// stay small on purpose so a 1080p-proxy scan stays well under the memory
// budget while the dimensions still exercise the full 1080p metadata path.
func SampleSize(spec Spec, sampleIdx int) int {
	h := sha256.New()
	var buf [16]byte
	binary.BigEndian.PutUint64(buf[0:], uint64(spec.Seed))
	binary.BigEndian.PutUint64(buf[8:], uint64(sampleIdx))
	h.Write(buf[:])
	sum := h.Sum(nil)
	// 256..1279 bytes, deterministic per (seed, index).
	return 256 + int(binary.BigEndian.Uint32(sum[0:])%1024)
}

// SampleData fills dst with the deterministic content for one sample.
// The same content is regenerated byte-for-byte by the receiver for
// checksum verification, so no source bytes need to be transported twice.
func SampleData(spec Spec, sampleIdx int, dst []byte) {
	size := SampleSize(spec, sampleIdx)
	if len(dst) < size {
		size = len(dst)
	}
	var counter uint32 = uint32(spec.Seed) ^ uint32(sampleIdx)*2654435761
	for i := 0; i < size; i++ {
		counter = counter*1103515245 + 12345
		dst[i] = byte(counter >> 16)
	}
}

// IsKeyframe reports whether a sample is a sync sample under the spec.
func (s Spec) IsKeyframe(sampleIdx int) bool {
	if s.KeyEvery <= 0 {
		return true
	}
	return sampleIdx%s.KeyEvery == 0
}

// SampleSpec carries the immutable identity of one sample across the
// transport layer.
type SampleSpec struct {
	Index    int
	Size     int
	Keyframe bool
}

// AllSamples expands the spec into the ordered sample list.
func (s Spec) AllSamples() []SampleSpec {
	out := make([]SampleSpec, s.SampleCount)
	for i := range out {
		out[i] = SampleSpec{
			Index: i, Size: SampleSize(s, i), Keyframe: s.IsKeyframe(i),
		}
	}
	return out
}
