func TestGenerateIsDeterministic(t *testing.T) {
	a, b := t.TempDir(), t.TempDir()
	if err := Generate(a); err != nil {
		t.Fatal(err)
	}
	if err := Generate(b); err != nil {
		t.Fatal(err)
	}
	rel := filepath.Join(CaseLossy, "hls", "video-00007.ts")
	da, err := os.ReadFile(filepath.Join(a, rel))
	if err != nil {
		t.Fatal(err)
	}
	db, err := os.ReadFile(filepath.Join(b, rel))
	if err != nil {
		t.Fatal(err)
	}
	if string(da) != string(db) {
		t.Fatal("generated bytes differ across runs")
	}
}

func TestGenerateLayoutAndFaults(t *testing.T) {
	dir := t.TempDir()
	if err := Generate(dir); err != nil {
		t.Fatal(err)
	}
	for _, c := range []string{CaseNormal, CaseLossy, CaseCorrupt} {
		for _, f := range []string{"index.m3u8", "video.m3u8", "presentation.mpd"} {
			if _, err := os.Stat(filepath.Join(dir, c, f)); err != nil {
				t.Fatalf("%s missing %s: %v", c, f, err)
			}
		}
	}
	// Lossy encodes a real wrap: the last video PTS must exceed 2^33.
	p := planFor(CaseLossy)
	first, last := videoPTS(0, p), videoPTS(SegmentCount-1, p)
	if last <= first {
		t.Fatalf("timeline did not advance: %d -> %d", first, last)
	}
	// The raw clock passes through the 33-bit wrap inside this timeline.
	if first%media.Wrap33 < last%media.Wrap33 {
		t.Fatalf("wrap not exercised: first=%d last=%d", first, last)
	}
	// Corrupt truncates exactly one fMP4 segment.
	data, err := os.ReadFile(filepath.Join(dir, CaseCorrupt, "dash", "audio-1-00012.m4s"))
	if err != nil {
		t.Fatal(err)
	}
	if len(data) != 40 {
		t.Fatalf("corrupt segment length=%d, want 40", len(data))
	}
}
