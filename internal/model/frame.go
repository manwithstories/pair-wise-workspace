package model

// AlgorithmVersion is mixed into every cache key and checkpoint. Bump it when
// any normalization or recovery decision changes.
const AlgorithmVersion = "pairflow/1.0.0"

// TimebaseHz is the shared nanosecond time base used by the synchronizer.
const TimebaseHz int64 = 1_000_000_000

// AudioSampleRateHz is the generated PCM rate.
const AudioSampleRateHz = 48_000

// Kind identifies a track's media type.
type Kind string

const (
	KindVideo Kind = "video"
	KindAudio Kind = "audio"
	KindData  Kind = "data"
)

// ColorMetadata is normalized before hashing/cache-key construction.
type ColorMetadata struct {
	Primaries string `json:"primaries"`
	Transfer  string `json:"transfer"`
	Matrix    string `json:"matrix"`
	Range     string `json:"range"`
}

// Normalize returns a canonical copy so equivalent spellings share a cache key.
func (c ColorMetadata) Normalize() ColorMetadata {
	out := c
	if out.Primaries == "" {
		out.Primaries = "bt709"
	}
	if out.Transfer == "" {
		out.Transfer = "bt709"
	}
	if out.Matrix == "" {
		out.Matrix = "bt709"
	}
	if out.Range == "" {
		out.Range = "limited"
	}
	return out
}

// Frame is one source image frame and its provenance metadata.
type Frame struct {
	TrackID           string        `json:"track_id"`
	TrackIndex        int           `json:"track_index"`
	Sequence          int64         `json:"sequence"`
	SourceOffset      int64         `json:"source_offset"`
	CapturedAtNS      int64         `json:"captured_at_ns"`
	RTPTimestamp      uint32        `json:"rtp_timestamp"`
	ExtendedTimestamp uint64        `json:"extended_timestamp"`
	PTSNS             int64         `json:"pts_ns"`
	DurationNS        int64         `json:"duration_ns"`
	Color             ColorMetadata `json:"color"`
	PayloadBytes      int           `json:"payload_bytes"`
	SHA256            string        `json:"sha256"`
	LocatorXOR        []byte        `json:"locator_xor,omitempty"`
	LocatorMask       uint64        `json:"locator_mask,omitempty"`
}

// Track groups frames on one independently clocked source.
type Track struct {
	ID          string  `json:"id"`
	Index       int     `json:"index"`
	Kind        Kind    `json:"kind"`
	SSRC        uint32  `json:"ssrc"`
	ClockRateHz uint32  `json:"clock_rate_hz"`
	StartRTP    uint32  `json:"start_rtp"`
	DriftPPM    float64 `json:"drift_ppm"`
	Frames      []Frame `json:"frames,omitempty"`
}

// AudioTrack is deterministic mono/stereo PCM generated by the prover.
type AudioTrack struct {
	ID         string `json:"id"`
	SampleRate int    `json:"sample_rate"`
	Channels   int    `json:"channels"`
	PTSNS      int64  `json:"pts_ns"`
	PCM        []byte `json:"-"`
	SHA256     string `json:"sha256"`
}

// Interval is an affected media interval on the nanosecond timeline.
type Interval struct {
	StartNS  int64 `json:"start_ns"`
	EndNS    int64 `json:"end_ns"`
	StartSeq int64 `json:"start_seq,omitempty"`
	EndSeq   int64 `json:"end_seq,omitempty"`
}

// FrameRecord is one stable JSONL output row.
type FrameRecord struct {
	Record       string        `json:"record"`
	TrackID      string        `json:"track_id"`
	TrackIndex   int           `json:"track_index"`
	Sequence     int64         `json:"sequence"`
	PTSNS        int64         `json:"pts_ns"`
	DurationNS   int64         `json:"duration_ns"`
	SourceOffset int64         `json:"source_offset"`
	SHA256       string        `json:"sha256"`
	Status       string        `json:"status"`
	ExtendedTS   uint64        `json:"extended_ts"`
	Issues       []*MediaError `json:"issues,omitempty"`
}

// GapRecord describes media that could not be recovered.
type GapRecord struct {
	Record    string   `json:"record"`
	TrackID   string   `json:"track_id"`
	Kind      string   `json:"kind"`
	Sequences []uint16 `json:"sequences,omitempty"`
	Interval  Interval `json:"interval"`
	Reason    string   `json:"reason"`
}
