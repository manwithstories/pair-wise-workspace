// sample is the materialised input for one run.
type sample struct {
	plan      fixture.Plan
	media     *manifest.Media
	Packets   []fixture.RPTPacket
	MP4Path   string
	Requests  []int64
	rtpErr    error
	syncFatal error
	// payloads maps segment id to its bytes, so hashes can be recomputed
	// independently of the manifest.
	payloads map[string][]byte
	// playlistHashes is the content commitment the playlist declared for
	// each segment, independent of the generated bytes.
	playlistHashes map[string]string
	faults         Faults
}

func buildSample(cfg Config) (*sample, *manifest.Media, error) {
	s := &sample{payloads: map[string][]byte{},
		playlistHashes: map[string]string{}, faults: cfg.Faults}
	cameras := cfg.Cameras
	if len(cameras) == 0 {
		cameras = []string{"cam0"}
	}
	// One playlist per camera, exactly like each camera uploading its own
	// media playlist. The parsed media are merged into one timeline.
	merged := &manifest.Media{Kind: "hls", Timescale: 1000}
	for i, cam := range cameras {
		plan := fixture.Generate(fixture.GenConfig{
			Seed: cfg.Seed + int64(i), Camera: cam, Segments: cfg.Segments,
			SegmentDurNS: cfg.SegmentDurNS, PPT: cfg.PacketRate,
			Faults: fixture.FaultSet{Reorder: cfg.Faults.Reorder,
				Drift: cfg.Faults.Drift, Drop: cfg.Faults.Drop,
				Wrap: cfg.Faults.Wrap},
		})
		s.plan.Segments = append(s.plan.Segments, plan.Segments...)
		playlist := fixture.HLSSegments(cam, plan.Segments)
		media, err := manifest.ParseHLSForTrack(bytes.NewReader([]byte(playlist)), manifest.DefaultLimits(), cam)
		if err != nil {
			return s, nil, err
		}
		// The playlist assigns its own media-sequence ids; bind each parsed
		// entry to the generated payload at the same position.
		for i, seg := range media.Segments {
			if i < len(plan.Segments) {
				s.payloads[seg.ID] = plan.Segments[i].Payload
			}
			s.playlistHashes[seg.ID] = seg.Hash
		}
		merged.Segments = append(merged.Segments, media.Segments...)
		if media.TargetDurNS > merged.TargetDurNS {
			merged.TargetDurNS = media.TargetDurNS
		}
	}
	s.media = merged
	// RTP observations come from the first camera, the one the recovery
	// stage replays.
	gen := fixture.Generate(fixture.GenConfig{
		Seed: cfg.Seed, Camera: cameras[0], Segments: cfg.Segments,
		SegmentDurNS: cfg.SegmentDurNS, PPT: cfg.PacketRate,
		Faults: fixture.FaultSet{Reorder: cfg.Faults.Reorder, Drift: cfg.Faults.Drift,
			Drop: cfg.Faults.Drop, Wrap: cfg.Faults.Wrap},
	})
	s.Packets = gen.Packets
	if cfg.Faults.Truncate && len(s.Packets) > 0 {
		// Truncation drops the tail: the last 10% of observations vanish.
		cut := len(s.Packets) - len(s.Packets)/10
		s.Packets = s.Packets[:cut]
	}
	// A 25 fps concert master: one frame per 40ms across the whole runtime,
	// with a 50-frame (2 second) sync-sample interval.
	frames := cfg.Segments * int(cfg.SegmentDurNS/40_000_000)
	if frames < 60 {
		frames = 60
	}
	s.MP4Path = cfg.WorkDir + "/source.mp4"
	// 25 fps at a 25kHz timescale is 1000 ticks per frame.
	if err := fixture.BuildMP4(s.MP4Path, frames, 25_000, 1000); err != nil {
		return s, nil, err
	}
	// Edit requests: a shot-locating lookup every four frames (160ms) at a
	// 40ms offset, i.e. between keyframes rather than on them, across the
	// indexed MP4 span.
	mp4Span := int64(frames) * 40_000_000
	for t := int64(40_000_000); t < mp4Span; t += 160_000_000 {
		s.Requests = append(s.Requests, t)
	}
	return s, merged, nil
}

func segID(s fixture.Segment) string {
	return fmt.Sprintf("%s-%06d", s.Track, s.Seq)
}

// HashOf returns the manifest's content commitment for a segment.
func (s *sample) HashOf(m manifest.Segment) string {
	return s.playlistHashes[m.ID]
}

// ManifestURI binds a manifest segment to the playlist entry it came from.
func (s *sample) ManifestURI(m manifest.Segment) string {
	return "playlist.m3u8#" + m.ID
}

// rtpDoc is the persisted shape of the RTP stage.
type rtpDoc struct {
	Delivered     int       `json:"delivered"`
	Received      int       `json:"received"`
	Duplicates    int       `json:"duplicates"`
	Late          int       `json:"late"`
	RecoveredGaps int       `json:"recovered_gaps"`
	FinalGaps     int       `json:"final_gaps"`
	MissingSeqs   uint64    `json:"missing_sequences"`
	Gaps          []rtp.Gap `json:"gaps"`
}

func recoverRTP(s *sample) rtpDoc {
	doc := rtpDoc{Received: len(s.Packets)}
	if len(s.Packets) == 0 {
		return doc
	}
	// Marshal every observation through pion/rtp and parse it back, so the
	// header handling exercised here is the same code a live feed uses.
	type obs struct {
		seq uint16
		ts  uint32
	}
	parsed := make([]obs, 0, len(s.Packets))
	for _, p := range s.Packets {
		dgram, err := (&pionrtp.Packet{Header: pionrtp.Header{
			Version: 2, SequenceNumber: p.Seq, Timestamp: p.Timestamp,
			SSRC: 0x1234,
		}, Payload: []byte{byte(p.Extended)}}).Marshal()
		if err != nil {
			s.rtpErr = err
			return doc
		}
		seq, ts, _, err := wire.ParsePacket(dgram)
		if err != nil {
			s.rtpErr = err
			return doc
		}
		parsed = append(parsed, obs{seq: seq, ts: ts})
	}
	ext := &wire.Extender{}
	first := ext.Extend(parsed[0].seq)
	r := rtp.NewReorderer("video", first, rtp.DefaultConfig())
	// A retransmission can only supply bytes that still exist upstream.
	// The venue is modelled as having no send-side copy once packets are
	// dropped or the feed is truncated, so those gaps must stay final.
	// A pure reorder leaves every byte available, so its gaps recover.
	retransmitAvailable := !s.faults.Drop && !s.faults.Truncate
	hook := func(g rtp.Gap) (rtp.Packet, bool) {
		if !retransmitAvailable {
			return rtp.Packet{}, false
		}
		return rtp.Packet{Seq: g.First, Track: g.Track}, true
	}
	for i, o := range parsed {
		var extSeq uint64
		if i == 0 {
			extSeq = first
		} else {
			extSeq = ext.Extend(o.seq)
		}
		_, _, _ = r.Push(rtp.Packet{Seq: extSeq, Timestamp: o.ts,
			Track: s.Packets[i].Track}, hook)
	}
	_, _ = r.Close(hook)
	doc.Delivered = r.Stats.Delivered
	doc.Duplicates = r.Stats.Duplicates
	doc.Late = r.Stats.Late
	doc.RecoveredGaps = r.Stats.Recovered
	doc.FinalGaps = r.Stats.FinalGaps
	doc.MissingSeqs = r.Stats.MissingSeqs
	doc.Gaps = r.FinalGaps()
	return doc
}

// jitterDoc is the persisted shape of the buffering stage.
type jitterDoc struct {
	Intervals []buffer.Interval `json:"intervals"`
	TargetNS  int64             `json:"target_ns"`
	HeldBytes int64             `json:"held_bytes"`
	Late      int               `json:"late"`
	Dropped   int               `json:"dropped"`
}

func runJitter(s *sample) jitterDoc {
	b := buffer.New("video", buffer.DefaultConfig())
	step := int64(40_000_000) // 25 observations per second
	var n int64
	for _, seg := range s.media.Segments {
		end := seg.StartNS + seg.DurNS
		for t := seg.StartNS; t < end; t += step {
			n++
			sample := buffer.Sample{Track: seg.Track, NS: t, Bytes: 1200}
			if s.faults.Drift {
				// The venue clock runs 200ppm fast; the buffer sees the
				// skewed arrivals and must still commit on the media axis.
				sample.NS = t + t*200/1_000_000
			}
			if s.faults.Reorder && n%97 == 0 {
				// A late observation for an interval already frozen.
				sample.NS = seg.StartNS - step
			}
			b.Push(sample)
		}
	}
	b.Flush()
	return jitterDoc{
		Intervals: b.Committed(),
		TargetNS:  b.TargetNS(),
		HeldBytes: b.HeldBytes(),
		Late:      b.LateCount(),
		Dropped:   b.Dropped(),
	}
}

// syncDoc is the persisted shape of the alignment stage.
type syncDoc struct {
	Corrections []sync.Correction `json:"corrections"`
	Errors      int               `json:"errors"`
	// Drift is the fitted audio-video clock relation. DriftFit is nil when
	// the fit was not uniquely determined, which is a hard stop rather than
	// a silent rewrite.
	Drift           *clock.DriftFit `json:"drift,omitempty"`
	DriftErr        string          `json:"drift_error,omitempty"`
	DriftBaselineNS int64           `json:"drift_baseline_ns,omitempty"`
	DriftPoints     int             `json:"drift_points,omitempty"`
}

func anchorsFor(s *sample, j jitterDoc) []clock.DriftPoint {
	// Alignment is computed on the first camera's video track, which the
	// buffer labels with the camera id rather than "video".
	videoTrack := s.media.Segments[0].Track
	if videoTrack == "" {
		videoTrack = "video"
	}
	var out []clock.DriftPoint
	last := int64(-1)
	for _, iv := range j.Intervals {
		if iv.Track != videoTrack {
			continue
		}
		for t := iv.StartNS; t <= iv.EndNS; t += 100_000_000 {
			if t == last {
				continue
			}
			last = t
			lag := int64(8_000_000)
			if s.faults.Drift {
				lag += t * 300 / 1_000_000
			}
			out = append(out, clock.DriftPoint{RefNS: t + lag, MediaNS: t})
		}
	}
	return out
}

func runSync(s *sample, j jitterDoc) syncDoc {
	al := sync.New("audio", sync.DefaultConfig())
	anchors := anchorsFor(s, j)
	for _, a := range anchors {
		al.Add(sync.Anchor{AudioNS: a.MediaNS, VideoNS: a.RefNS})
	}
	var doc syncDoc
	for _, iv := range j.Intervals {
		if _, err := al.CorrectInterval(iv.StartNS, iv.EndNS); err != nil {
			doc.Errors++
			var ce *clock.Error
			if errors.As(err, &ce) && ce.Code == clock.CodeSyncThreshold {
				s.syncFatal = err
			}
		}
	}
	doc.Corrections = al.Corrections()
	// Fit the audio clock against the video reference over a bounded window
	// of anchors. The venue drift grows without bound, so the fit is scoped
	// to the first hour of runtime: anchor points, not experiment length,
	// vary the answer, and an ambiguous fit is reported rather than used to
	// silently shift the timeline.
	if s.faults.Drift && len(j.Intervals) > 0 {
		window := int64(3600) * 1_000_000_000
		var probe []clock.DriftPoint
		for _, dp := range anchors {
			if dp.RefNS > window && len(probe) >= clock.DefaultFitConfig().MinPoints {
				break
			}
			probe = append(probe, dp)
		}
		fit, err := clock.FitDrift(probe, clock.DefaultFitConfig())
		if err != nil {
			doc.DriftErr = err.Error()
		} else {
			doc.Drift = &fit
			doc.DriftBaselineNS = probe[len(probe)-1].RefNS
			doc.DriftPoints = len(probe)
		}
	}
	return doc
}

// checkSegmentHashes recomputes each segment hash from its bytes and compares
// it with the commitment carried by the manifest.
func checkSegmentHashes(s *sample, limits manifest.Limits) (float64, []error) {
	var match int
	var errs []error
	for _, seg := range s.media.Segments {
		body, ok := s.payloads[seg.ID]
		if !ok {
			errs = append(errs, fmt.Errorf("segment %s missing payload", seg.ID))
			continue
		}
		if err := limits.CheckSegment(seg.ID, int64(len(body))); err != nil {
			errs = append(errs, err)
			continue
		}
		h := txn.HashBytes(body)
		if committed := s.playlistHashes[seg.ID]; committed != "" && h != committed {
			errs = append(errs, fmt.Errorf("segment %s hash mismatch", seg.ID))
			continue
		}
		match++
	}
	if len(s.media.Segments) == 0 {
		return 0, nil
	}
	return float64(match) / float64(len(s.media.Segments)), errs
}
