package pipeline

import (
	"fmt"

	"avcheck/internal/fixture"
	"avcheck/internal/transport"
)

// Case names a demo scenario.
type Case string

const (
	CaseClean            Case = "clean"
	CaseBurstReorderSlow Case = "burst-reorder-slow"
	CaseTruncatedVint    Case = "truncated-vint"
	CaseDoubleLoss       Case = "double-loss"
	CaseOversize         Case = "oversize-element"
	CaseUnknownTrack     Case = "unknown-track"
	CaseCycle            Case = "dependency-cycle"
)

// Cases lists every selectable case for the CLI help.
var Cases = []Case{CaseClean, CaseBurstReorderSlow, CaseTruncatedVint, CaseDoubleLoss, CaseOversize, CaseUnknownTrack, CaseCycle}

// Scenario binds a demo case to its fixture spec, link profile and expected
// recovery grades.
type Scenario struct {
	Case        Case
	Spec        fixture.Spec
	Link        transport.LinkConfig
	TargetBps   int64
	MemoryBytes int64
	// ExpectCommitted is false for inputs that must not yield a manifest.
	ExpectCommitted bool
	// Corrupt, when set, damages the generated bytes and returns the byte
	// offset that was hit.
	Corrupt func([]byte) ([]byte, int64, error)
}

// ScenarioFor resolves a case name into a ready-to-run scenario.
func ScenarioFor(c Case, seed int64, targetBps, memoryBytes int64) (Scenario, error) {
	spec := fixture.DefaultSpec(seed)
	sc := Scenario{Case: c, Spec: spec, TargetBps: targetBps, MemoryBytes: memoryBytes, ExpectCommitted: true}
	base := transport.LinkConfig{GroupSize: 16, JitterNs: 15_000_000}
	switch c {
	case CaseClean:
		sc.Link = base
	case CaseBurstReorderSlow:
		sc.Link = base
		sc.Link.JitterNs = 120_000_000
		sc.Link.DropSinglesEvery = 3
		sc.Link.DuplicateEvery = 5
		sc.Link.ReorderEvery = 2
		sc.Link.MaxInFlight = 24
		sc.Link.BurstGroups = 1
	case CaseTruncatedVint:
		sc.ExpectCommitted = false
		sc.Corrupt = truncateVint
	case CaseDoubleLoss:
		sc.Link = base
		sc.Link.DropSinglesEvery = 4
		sc.Link.DoubleLossGroup = 2
	case CaseOversize:
		sc.ExpectCommitted = false
		sc.Corrupt = oversizeElement
	case CaseUnknownTrack:
		sc.ExpectCommitted = false
		spec.Tracks = append(spec.Tracks, fixture.TrackSpec{
			Number: 9, UID: 0x109, Kind: "cue", Codec: "AVCHECK_CUE", Name: "orphan",
			Frames: 1, StartNs: 0, StepNs: 100_000_000, Payload: 8, Depends: []uint64{99},
		})
		sc.Spec = spec
	case CaseCycle:
		sc.ExpectCommitted = false
		spec.Tracks[0].Depends = []uint64{2}
		spec.Tracks[1].Depends = []uint64{1}
		sc.Spec = spec
	default:
		return Scenario{}, fmt.Errorf("pipeline: unknown case %q (want one of %v)", c, Cases)
	}
	return sc, nil
}

// BuildScenario renders the scenario's fixture and applies any targeted
// corruption, returning the exact bytes the CLI would analyse.
func BuildScenario(sc Scenario) ([]byte, error) {
	sample, err := fixture.Build(sc.Spec)
	if err != nil {
		return nil, err
	}
	data := sample.Bytes
	if sc.Corrupt != nil {
		data, _, err = sc.Corrupt(data)
		if err != nil {
			return nil, err
		}
	}
	return data, nil
}
