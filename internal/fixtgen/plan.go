// Package fixtgen produces reproducible source packages for the archive
// pipeline. All media bytes are synthetic but structurally valid ISO-BMFF and
// RTP/H.264; nothing references external material.
package fixtgen

import (
	"encoding/binary"
	"math/rand"
)

// SegmentCount and TrackCount define the canonical 12-segment, 3-track batch.
const (
	SegmentCount = 12
	TrackCount   = 3
	SamplesPerTrack = 12
	KeyEvery        = 3 // every 3rd video sample is an IDR sync sample
)

// Fault describes an injected defect. Values are stable for reproducibility.
type Fault string

const (
	FaultNone          Fault = ""
	FaultTruncated     Fault = "truncated"      // tail cut, last complete sample survives
	FaultBadLength     Fault = "bad_length"     // corrupt mdat/box length field
	FaultMissingIndex  Fault = "missing_index"  // stss removed; keyframes rebuilt
	FaultCorruptIndex  Fault = "corrupt_index"  // stss lies; rebuilt scan ignores it
	FaultForgedCache   Fault = "forged_cache"   // cache entry digest does not match
	FaultUnsupported   Fault = "unsupported"    // one track uses an unknown codec
	FaultIncompleteFrag Fault = "incomplete_frag" // fragmented moof with missing sample
	FaultRTPTruncated  Fault = "rtp_truncated"  // RTP capture cut inside FU-A
)

// TrackSpec names the three fixture tracks.
type TrackSpec struct {
	ID      int
	Codec   string
	Handler string
}

// Tracks returns the canonical three-track layout.
func Tracks() []TrackSpec {
	return []TrackSpec{
		{1, "avc1", "vide"},
		{2, "mp4a", "soun"},
		{3, "text", "text"},
	}
}

// Segment is one generated source package.
type Segment struct {
	ID     string // seg01 .. seg12
	Index  int
	Fault  Fault
	Source string // relative path of the primary source file
}

// Plan returns the deterministic fault placement across the 12 segments.
// Exactly one segment (seg07) is unrecoverable; the rest exercise recovery.
func Plan() []Segment {
	faults := []Fault{
		FaultNone,           // seg01 clean
		FaultNone,           // seg02 clean
		FaultTruncated,      // seg03 tail cut
		FaultBadLength,      // seg04 corrupt length -> recovered after isolation? no: fatal
		FaultMissingIndex,   // seg05 no stss -> rebuild
		FaultCorruptIndex,   // seg06 lying stss -> rebuild
		FaultUnsupported,    // seg07 unsupported codec -> quarantined (the 1)
		FaultNone,           // seg08 clean
		FaultIncompleteFrag, // seg09 fragmented, incomplete fragment
		FaultRTPTruncated,   // seg10 RTP capture cut in FU-A
		FaultForgedCache,    // seg11 cache digest forged -> reject & recompute
		FaultNone,           // seg12 clean
	}
	out := make([]Segment, SegmentCount)
	for i := range out {
		id := segmentID(i)
		out[i] = Segment{ID: id, Index: i, Fault: faults[i], Source: id + ".mp4"}
	}
	return out
}

func segmentID(i int) string {
	return "seg" + pad(i+1)
}

func pad(n int) string {
	if n < 10 {
		return "0" + string(rune('0'+n))
	}
	return string(rune('0'+n/10)) + string(rune('0'+n%10))
}

// rngFor returns a deterministic RNG stream for a segment/track pair so the
// generated bytes are reproducible byte-for-byte across runs.
func rngFor(seg, track int) *rand.Rand {
	return rand.New(rand.NewSource(int64(seg*1000 + track)))
}

// makeSample returns deterministic coded bytes for one sample. Video samples
// are AVCC-framed NAL units with a recognizable IDR marker; audio and text
// samples are opaque codec payloads the remuxer copies untouched.
func makeSample(seg, track, sampleIdx int, codec string) []byte {
	rng := rngFor(seg, track)
	switch codec {
	case "avc1":
		nalType := byte(1) // non-IDR slice
		isKey := sampleIdx%KeyEvery == 0
		if isKey {
			nalType = 5 // IDR
		}
		payload := make([]byte, 16+sampleIdx%4)
		rng.Read(payload)
		payload[0] = 0x65 &^ 0x1F | nalType
		nal := append([]byte{payload[0]}, payload[1:]...)
		out := make([]byte, 4+len(nal))
		binary.BigEndian.PutUint32(out, uint32(len(nal)))
		copy(out[4:], nal)
		return out
	case "mp4a":
		b := make([]byte, 8+sampleIdx%3)
		rng.Read(b)
		return b
	default: // text
		b := []byte("subtitle-")
		b = append(b, byte('0'+seg), byte('0'+sampleIdx%10))
		return b
	}
}

// SampleData exposes the generator so tests can assert byte-for-byte roundtrip.
func SampleData(seg, track, sampleIdx int, codec string) []byte {
	return makeSample(seg, track, sampleIdx, codec)
}
