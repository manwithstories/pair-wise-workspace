class CliTests(unittest.TestCase):
    def _run(self, *argv: str) -> int:
        import contextlib
        import io

        stream = io.StringIO()
        with contextlib.redirect_stdout(stream), contextlib.redirect_stderr(stream):
            try:
                return cli.main(list(argv))
            except SystemExit as exc:  # argparse usage errors
                return int(exc.code or 0)

    def test_success_path_exits_zero_and_prints_metrics(self):
        with Workspace() as work:
            manifest = work / "manifest.json"
            self.assertEqual(
                self._run(
                    "archive", "--input", str(fixtures() / "good.mkv"),
                    "--manifest", str(manifest),
                    "--rate", "48000", "--layout", "stereo", "--lufs", "-16",
                ),
                0,
            )
            self.assertEqual(
                self._run(
                    "verify", "--manifest", str(manifest),
                    "--fixtures", str(fixtures()), "--self-test",
                ),
                0,
            )

    def test_usage_error_exits_two(self):
        self.assertEqual(self._run("archive", "--rate", "not-a-number"), 2)
        self.assertEqual(self._run("verify"), 2)

    def test_failed_input_exits_one(self):
        with Workspace() as work:
            result = self._run(
                "archive", "--input", str(work / "missing.mkv"),
                "--manifest", str(work / "m.json"),
            )
            self.assertEqual(result, 1)

    def test_unsupported_rate_is_a_usage_error(self):
        with Workspace() as work:
            self.assertEqual(
                self._run(
                    "archive", "--input", str(fixtures() / "good.mkv"),
                    "--manifest", str(work / "m.json"), "--rate", "22050",
                ),
                2,
            )

    def test_probe_command_reports_streams(self):
        self.assertEqual(
            self._run("probe", "--input", str(fixtures() / "good.mkv")), 0
        )


