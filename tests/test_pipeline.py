class ClockTests(unittest.TestCase):
    def test_unwrap_single_wrap(self):
        result = unwrap_counter([252, 253, 0, 1, 2], 8)
        self.assertEqual(result.values, [252, 253, 256, 257, 258])
        self.assertEqual(result.wraps, 1)

    def test_unwrap_rejects_indistinguishable_multi_wrap(self):
        with self.assertRaises(AmbiguousWrapError):
            unwrap_counter([100, 20], 8)  # backward gap 176 > half modulus
        with self.assertRaises(AmbiguousWrapError):
            unwrap_counter([0, 129], 8)   # forward gap 129 > half modulus

    def test_unwrap_half_modulus_gap_is_unique(self):
        # A gap of exactly half the modulus has a single shortest explanation.
        result = unwrap_counter([0, 128], 8)
        self.assertEqual(result.wraps, 0)
        self.assertEqual(result.values, [0, 128])

    def test_drift_fit_recovers_injected_ppm(self):
        rate = 1_000_000
        clocks = [i * 1000 for i in range(50)]
        refs = [round(c * 1000 * 1.0001) for c in clocks]  # +100 ppm
        model = fit_drift(clocks, refs, rate)
        self.assertAlmostEqual(model.drift_ppm, 100.0, delta=1.0)
        self.assertEqual(model.to_reference(clocks[10]), refs[10])


class ProbeTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_roundtrip_good_file(self):
        spec = FixtureSpec("t.mmx", "t", 10, 16, 32, 0.0, 0)
        build_clean_track(self.tmp / spec.name, spec)
        result = parse_track_file(self.tmp / spec.name)
        self.assertTrue(result.ok, [e.describe() for e in result.errors])
        self.assertEqual(len(result.frames), 10)
        self.assertGreater(result.frames[0].header_offset, 0)

    def test_truncated_header_reports_exact_offset(self):
        truth = build_truncated_track(self.tmp / "truncated.mmx")
        result = parse_track_file(self.tmp / truth.name)
        self.assertEqual(len(result.errors), 1)
        self.assertEqual(result.errors[0].offset, truth.expected_offset)
        self.assertIn("truncated", result.errors[0].describe())

    def test_bad_digest_reports_payload_offset_and_seq(self):
        truth = build_bad_digest_track(self.tmp / "badhash.mmx")
        result = parse_track_file(self.tmp / truth.name)
        self.assertEqual(len(result.errors), 1)
        self.assertIsInstance(result.errors[0], MediaMixError)
        self.assertEqual(result.errors[0].offset, truth.expected_offset)
        self.assertEqual(result.errors[0].frame_seq, truth.expected_frame_seq)

    def test_header_size_matches_format(self):
        self.assertEqual(struct.calcsize(FRAME_HEADER_FORMAT), FRAME_HEADER_SIZE)

    def test_illegal_metadata_rejected(self):
        from mediamix.probe import _validate_frame_header, make_frame_header
        from mediamix.model import MetadataError

        # Width/height live in the header; the payload length cross-check runs
        # after the field-range checks, so a small payload is sufficient here.
        payload = bytes(2 * 2 * 3)
        cases = [
            dict(fps_num=30, fps_den=0, width=2, height=2, color_primaries="709", transfer="1886"),
            dict(fps_num=30, fps_den=1, width=99999, height=2, color_primaries="709", transfer="1886"),
            dict(fps_num=30, fps_den=1, width=2, height=2, color_primaries="zzzz", transfer="1886"),
        ]
        for kwargs in cases:
            with self.subTest(kwargs=kwargs):
                hdr = make_frame_header(0, 0, payload, **kwargs)
                with self.assertRaises(MetadataError):
                    _validate_frame_header(hdr, 0, "t")


class TimelineDiagnosticTests(unittest.TestCase):
    def _frame(self, track, seq, tick, priority_pos=0):
        from mediamix.timeline import MappedFrame

        return MappedFrame(
            track_id=track, file_seq=seq, frame_seq=seq, tick=tick,
            width=4, height=4, fps_num=30, fps_den=1,
            color_primaries="709", transfer="1886",
        )

    def test_overlap_and_tolerance_diagnostics(self):
        from mediamix.timeline import TrackTimeline, merge_tracks

        high = TrackTimeline(track_id="hi", priority=0)
        high.frames = [self._frame("hi", 0, 1000), self._frame("hi", 1, 5000)]
        low = TrackTimeline(track_id="lo", priority=1)
        # Exact same tick -> overlap (hi wins); near tick -> tolerance.
        low.frames = [self._frame("lo", 0, 1000), self._frame("lo", 1, 5001)]
        merged = merge_tracks([high, low], tolerance_ticks=1000)
        kinds = {d.kind for d in merged.diagnostics}
        self.assertIn("overlap", kinds)
        self.assertIn("tolerance", kinds)
        # Overlap drops the lower-priority duplicate tick.
        ticks = [f.tick for f in merged.frames]
        self.assertEqual(len(ticks), len(set(ticks)))
        self.assertTrue(all(f.track_id == "hi" for f in merged.frames if f.tick == 1000))

    def test_backward_and_missing_frame_diagnostics(self):
        from mediamix.timeline import TrackTimeline
        from mediamix.clock import DriftModel
        from fractions import Fraction
        from types import SimpleNamespace
        from mediamix.timeline import map_track

        # Identity clock map so ticks equal the supplied clock values.
        model = DriftModel(slope=Fraction(1), intercept=Fraction(0), n=2)
        records = [
            SimpleNamespace(header=SimpleNamespace(
                seq=0, clock=100, fps_num=30, fps_den=1, width=4, height=4,
                color_primaries="709", transfer="1886"), file_seq=0),
            SimpleNamespace(header=SimpleNamespace(
                seq=5, clock=50, fps_num=30, fps_den=1, width=4, height=4,
                color_primaries="709", transfer="1886"), file_seq=1),
        ]
        tt = map_track(
            "t", 0, records,
            unwrapped_seq=[0, 5], unwrapped_clock=[100, 50],
            drift_model=model, wraps=0,
        )
        kinds = {d.kind for d in tt.diagnostics}
        self.assertIn("backward_time", kinds)
        self.assertIn("missing_frame", kinds)


class PathSafetyTests(unittest.TestCase):
    def test_path_traversal_rejected(self):
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaises(PathEscapeError):
                safe_resolve(d, "..", "escape.mmx")

    def test_nested_path_contained(self):
        with tempfile.TemporaryDirectory() as d:
            p = safe_resolve(d, "a", "b", "c.mmx")
            self.assertTrue(str(p).startswith(str(Path(d).resolve())))


class RenderTests(unittest.TestCase):
    def test_png_roundtrip(self):
        rgb = np.zeros((12, 24, 3), dtype=np.uint8)
        rgb[..., 0] = 200
        blob = encode_png(rgb)
        decoded = decode_png(blob)
        self.assertEqual(decoded.shape, (12, 24, 3))
        np.testing.assert_array_equal(decoded, rgb)


class PipelineIntegrationTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.wd = Path(self._tmp.name)
        self.truths = generate_fixtures(self.wd)
        self.names = fixture_input_names()
        self.params = PipelineParams(
            inputs=self.names, out_width=160, out_height=90
        )

    def tearDown(self):
        self._tmp.cleanup()

    def test_full_run_isolates_bad_tracks_and_validates(self):
        result = run_pipeline(self.wd, self.params)
        self.assertEqual(len(result.validation_errors), 0)
        self.assertEqual(len(result.isolated_tracks), 2)
        self.assertGreaterEqual(result.frames_written, 120)
        self.assertGreaterEqual(result.wraps, 1)
        self.assertEqual(len(result.output_sha256), 64)
        # Independent validator agrees.
        manifest = json.loads((self.wd / "frames" / "manifest.json").read_text())
        self.assertEqual(validate_export(self.wd, manifest), [])

    def test_corruption_offsets_are_exact(self):
        truth = {t.name: t for t in self.truths}
        for name in ("truncated.mmx", "badhash.mmx"):
            parsed = parse_track_file(self.wd / "inputs" / name)
            self.assertEqual(parsed.errors[0].offset, truth[name].expected_offset)

    def test_resume_skips_verified_frames(self):
        first = run_pipeline(self.wd, self.params, interrupt_after=INTERRUPT_AFTER)
        self.assertTrue(first.interrupted)
        frames_after_crash = len(list((self.wd / "frames").glob("frame_*.png")))
        second = run_pipeline(self.wd, self.params)
        self.assertFalse(second.interrupted)
        self.assertEqual(second.frames_skipped, frames_after_crash)
        self.assertEqual(second.validation_errors, [])

    def test_stale_input_rejected_on_resume(self):
        run_pipeline(self.wd, self.params, interrupt_after=INTERRUPT_AFTER)
        # Mutate an input after the checkpoint was written.
        target = self.wd / "inputs" / "studio.mmx"
        blob = bytearray(target.read_bytes())
        blob[-1] ^= 0x01
        target.write_bytes(bytes(blob))
        with self.assertRaises(CheckpointConflictError):
            run_pipeline(self.wd, self.params)

    def test_parameter_change_rejected_on_resume(self):
        run_pipeline(self.wd, self.params, interrupt_after=INTERRUPT_AFTER)
        changed = PipelineParams(inputs=self.names, out_width=320, out_height=180)
        with self.assertRaises(CheckpointConflictError):
            run_pipeline(self.wd, changed)

    def test_strict_mode_fails_on_corruption(self):
        strict = PipelineParams(inputs=self.names, strict=True)
        with self.assertRaises(MediaMixError):
            run_pipeline(self.wd, strict)


class CliTests(unittest.TestCase):
    def test_demo_and_verify_exit_zero(self):
        with tempfile.TemporaryDirectory() as d:
            workdir = str(Path(d) / "demo")
            self.assertEqual(cli_main(["demo", "--workdir", workdir, "--json"]), 0)
            self.assertEqual(cli_main(["verify", "--workdir", workdir, "--json"]), 0)

    def test_verify_flags_tampered_frame(self):
        with tempfile.TemporaryDirectory() as d:
            workdir = Path(d) / "demo"
            cli_main(["demo", "--workdir", str(workdir)])
            first = next((workdir / "frames").glob("frame_*.png"))
            blob = bytearray(first.read_bytes())
            blob[40] ^= 0xFF
            first.write_bytes(bytes(blob))
            code = cli_main(["verify", "--workdir", str(workdir), "--json"])
            self.assertEqual(code, 4)


