_FIXTURE_CACHE: dict[str, Path] = {}


def fixtures() -> Path:
    """Generate the fixture set once and reuse it for every test."""
    if "dir" not in _FIXTURE_CACHE:
        directory = Path(tempfile.mkdtemp(prefix="mediarc-fixtures-"))
        make_fixtures.generate(directory)
        _FIXTURE_CACHE["dir"] = directory
    return _FIXTURE_CACHE["dir"]


def tearDownModule() -> None:  # noqa: N802 - unittest hook name
    directory = _FIXTURE_CACHE.pop("dir", None)
    if directory is not None:
        shutil.rmtree(directory, ignore_errors=True)


class Workspace:
    """Per-test scratch directory, removed on exit."""

    def __enter__(self) -> Path:
        self.path = Path(tempfile.mkdtemp(prefix="mediarc-test-"))
        return self.path

    def __exit__(self, *exc: object) -> None:
        shutil.rmtree(self.path, ignore_errors=True)


