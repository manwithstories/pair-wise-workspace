class RecoveryTests(unittest.TestCase):
    def test_damage_is_located_at_a_source_byte_offset(self):
        result = probe(str(fixtures() / "damaged.mp4"))
        damage = integrity_scan(result)
        self.assertEqual(len(damage), 1)
        self.assertIsInstance(damage[0].offset, int)
        self.assertGreaterEqual(damage[0].offset, 0)
        self.assertLess(damage[0].offset, result.size)
        error = damage[0].error(result.path, result.time_base)
        self.assertIn(f"offset={damage[0].offset}", error.render())

    def test_recoverable_damage_is_repaired_from_a_safe_boundary(self):
        result = probe(str(fixtures() / "damaged.mp4"))
        damage = integrity_scan(result)[0]
        with Workspace() as work:
            segment = SegmentRecord("s0", damage.stream_index, 0, 1, "", "")
            recovered = recover(result, segment, damage, str(work))
            self.assertTrue(recovered.path)
            self.assertTrue(Path(recovered.path).exists())
            self.assertGreater(recovered.salvaged_ticks, 0)
            self.assertIsNotNone(recovered.resume_offset)

    def test_unrecoverable_damage_declines_instead_of_faking_success(self):
        result = probe(str(fixtures() / "damaged.mkv"))
        damage = integrity_scan(result)
        self.assertTrue(damage)
        with Workspace() as work:
            segment = SegmentRecord("s0", damage[0].stream_index, 0, 1, "", "")
            recovered = recover(result, segment, damage[0], str(work))
            self.assertEqual(recovered.path, "")
            self.assertEqual(recovered.salvaged_ticks, 0)

    def test_incomplete_keyframe_index_is_detected(self):
        result = probe(str(fixtures() / "keyframe_index.mp4"))
        from mediarc.verify import _index_checks

        checks = _index_checks(result, None)
        self.assertTrue(checks)
        self.assertFalse(checks[0].ok)
        self.assertEqual(checks[0].missing, [97])

    def test_manifest_detects_tampered_segment_file(self):
        with Workspace() as work:
            manifest_path = work / "manifest.json"
            archive(
                str(fixtures() / "good.mkv"), str(manifest_path),
                work_dir=str(work / "work"), limits=Limits(jobs=1),
            )
            manifest = Manifest.loads(manifest_path.read_text())
            video = next(s for s in manifest.segments if s.keyframe_ticks)
            Path(video.path).write_bytes(b"tampered")
            verification = verify_manifest(manifest, source_path=str(fixtures() / "good.mkv"))
            self.assertEqual(verification.hash_ok, verification.hash_total - 1)
            self.assertFalse(verification.ok)

    def test_tampered_keyframe_digest_is_a_verification_failure(self):
        with Workspace() as work:
            manifest_path = work / "manifest.json"
            archive(
                str(fixtures() / "good.mkv"), str(manifest_path),
                work_dir=str(work / "work"), limits=Limits(jobs=1),
            )
            manifest = Manifest.loads(manifest_path.read_text())
            video = next(s for s in manifest.segments if s.keyframe_ticks)
            video.keyframe_ticks = video.keyframe_ticks + [12345]
            verification = verify_manifest(manifest, source_path=str(fixtures() / "good.mkv"))
            self.assertFalse(verification.ok)
            self.assertLess(verification.keyframe_hit_rate, 1.0)
            self.assertIn(
                "verification-failed", {e.code for e in verification.errors}
            ) or self.assertIn(
                "keyframe-index-incomplete", {e.code for e in verification.errors}
            )


