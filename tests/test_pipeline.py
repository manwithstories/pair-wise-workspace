class TimeBaseTests(unittest.TestCase):
    def test_rate_is_lcm_of_video_and_audio_factors(self):
        rate = choose_timeline_rate(
            [Rational(1, 1000), Rational(1, 90000)], [48000]
        )
        self.assertEqual(rate, Rational(720000, 1))
        base = TimeBase(rate)
        # 1/24 s is exact on this base, so the conversion must be lossless.
        ticks, exact = base.to_ticks_checked(Fraction(1, 24))
        self.assertTrue(exact)
        self.assertEqual(base.to_seconds(ticks), Fraction(1, 24))

    def test_incommensurate_rate_reports_inexact_conversion(self):
        base = TimeBase(48000)
        ticks, exact = base.to_ticks_checked(Fraction(1, 7))
        self.assertFalse(exact)
        # The error is bounded by half a tick, never unbounded drift.
        self.assertLessEqual(
            abs(base.to_seconds(ticks) - Fraction(1, 7)), Fraction(1, 2 * 48000)
        )

    def test_negative_timestamps_are_reported_with_source_offset(self):
        base = TimeBase(48000)
        issues = analyze_timestamps(
            0,
            [(0, -5, None, 100), (1, 48000, 48000, 200)],
            Rational(1, 48000),
            base,
        )
        self.assertEqual([i.code for i in issues], ["negative-timestamp"])
        error = issues[0].error("clip.mkv")
        self.assertEqual(error.offset, 100)
        self.assertEqual(error.stage, "timeline")
        self.assertIn("offset=100", error.render())

    def test_non_monotonic_and_rounding_collision(self):
        base = TimeBase(10)
        entries = [
            (0, 0, 0, 10),
            (1, 1, 2, 20),
            (2, 2, 1, 30),  # DTS regresses
            (3, 1, 3, 40),  # PTS 0.1s and 0.2s both round from ticks 1/2
        ]
        codes = [i.code for i in analyze_timestamps(0, entries, Rational(1, 10), base)]
        self.assertIn("non-monotonic-timestamp", codes)


class TimelineModelTests(unittest.TestCase):
    def _timeline(self) -> Timeline:
        base = TimeBase(48000)
        tracks = [
            Track(0, "video", "h264", Rational(1, 1000), 0, 96_000),
            Track(1, "audio", "pcm_s16le", Rational(1, 1000), 0, 96_000),
        ]
        return Timeline(
            base, 96_000, tracks,
            contiguous_segments(0, [48_000], 96_000, prefix="v"),
        )

    def test_contiguous_segments_cover_the_track_exactly(self):
        timeline = self._timeline()
        spans = [(s.start_ticks, s.end_ticks) for s in timeline.segments]
        self.assertEqual(spans, [(0, 48_000), (48_000, 96_000)])
        self.assertEqual(timeline.segments[1].source_start_ticks, 48_000)

    def test_edit_point_beyond_track_is_rejected(self):
        timeline = self._timeline()
        timeline.segments.append(Segment("v99", 0, 48_000, 200_000))
        codes = [e.code for e in timeline.validate(path="x.mkv")]
        self.assertIn("edit-out-of-range", codes)

    def test_transition_must_sit_inside_both_segments(self):
        timeline = self._timeline()
        from mediarc.timeline import Transition

        # Segments here touch but do not overlap, so a transition must fail.
        timeline.transitions = [Transition("t0", "v00", "v01", 40_000, 48_000)]
        self.assertEqual(
            [e.code for e in timeline.validate()], ["transition-overlap"]
        )
        # A real overlap is legal exactly when a transition covers all of it.
        timeline.segments[1].start_ticks = 40_000
        timeline.segments[1].source_start_ticks = 40_000
        self.assertEqual([e.code for e in timeline.validate()], [])

    def test_timeline_round_trips_through_dict(self):
        timeline = self._timeline()
        self.assertEqual(Timeline.from_dict(timeline.to_dict()).to_dict(), timeline.to_dict())


