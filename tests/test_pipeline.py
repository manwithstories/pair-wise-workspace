class PipelineTests(unittest.TestCase):
    def test_archive_produces_hashed_segments_and_then_verifies(self):
        with Workspace() as work:
            manifest_path = work / "manifest.json"
            report = archive(
                str(fixtures() / "good.mkv"),
                str(manifest_path),
                rate=48_000,
                layout="stereo",
                lufs=-16.0,
                work_dir=str(work / "work"),
                limits=Limits(jobs=2),
            )
            self.assertEqual(report.healthy, 4)
            self.assertEqual(report.failed, 0)
            manifest = Manifest.loads(manifest_path.read_text())
            verification = verify_manifest(manifest)
            self.assertEqual(verification.roundtrip_rate, 1.0)
            self.assertEqual(verification.keyframe_hit_rate, 1.0)
            self.assertEqual(verification.hash_ok, verification.hash_total)
            self.assertEqual(verification.audio_ok, verification.audio_total)
            self.assertTrue(verification.ok)

    def test_resume_reuses_matching_stages(self):
        with Workspace() as work:
            common = dict(
                rate=48_000, layout="stereo", lufs=-16.0,
                work_dir=str(work / "work"), limits=Limits(jobs=1),
            )
            archive(str(fixtures() / "good.mkv"), str(work / "a.json"), **common)
            second = archive(
                str(fixtures() / "good.mkv"), str(work / "b.json"), resume=True, **common
            )
            self.assertIn("probe", second.resumed_stages)
            self.assertIn("timeline", second.resumed_stages)
            self.assertIn("transform", second.resumed_stages)
            self.assertEqual(
                Manifest.loads((work / "a.json").read_text()).digest(),
                Manifest.loads((work / "b.json").read_text()).digest(),
            )

