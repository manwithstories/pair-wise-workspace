class ManifestTests(unittest.TestCase):
    def _archive(self, work: Path) -> Manifest:
        archive(
            str(fixtures() / "good.mkv"),
            str(work / "manifest.json"),
            work_dir=str(work / "work"),
            limits=Limits(jobs=1),
        )
        return Manifest.loads((work / "manifest.json").read_text())

    def test_manifest_round_trips_losslessly(self):
        with Workspace() as work:
            manifest = self._archive(work)
            again = Manifest.loads(manifest.dumps())
            self.assertEqual(again.to_dict(), manifest.to_dict())
            self.assertEqual(again.digest(), manifest.digest())

    def test_manifest_bytes_are_deterministic(self):
        with Workspace() as work:
            manifest = self._archive(work)
            self.assertEqual(manifest.dumps(), Manifest.loads(manifest.dumps()).dumps())

    def test_manifest_is_identical_across_job_counts(self):
        with Workspace() as work:
            directory = work / "run"
            common = dict(rate=48_000, layout="stereo", lufs=-16.0)
            archive(
                str(fixtures() / "good.mkv"), str(directory / "m.json"),
                work_dir=str(directory / "w"), limits=Limits(jobs=1), **common,
            )
            first = (directory / "m.json").read_text()
            shutil.rmtree(directory)
            archive(
                str(fixtures() / "good.mkv"), str(directory / "m.json"),
                work_dir=str(directory / "w"), limits=Limits(jobs=2), **common,
            )
            second = (directory / "m.json").read_text()
            self.assertEqual(first, second)

    def test_missing_fields_are_rejected_with_schema_error(self):
        with self.assertRaises(MediaError) as caught:
            Manifest.loads('{"schema": "mediarc.manifest/v1", "schema_version": 1}')
        self.assertEqual(caught.exception.code, "manifest-schema")

    def test_corrupt_json_is_rejected(self):
        with self.assertRaises(MediaError) as caught:
            Manifest.loads("{not json")
        self.assertEqual(caught.exception.code, "manifest-corrupt")


