"""Programmatically generated test fixtures.

Everything is synthesised at run time: no binary assets are checked in.  Normal
assets are encoded with PyAV across MOV/MP4/MKV and multi-track / mixed sample
rate / transition layouts.  Damaged assets are produced two ways:

* truncation and payload corruption are byte-level surgery on a healthy file
  (the only faithful way to reproduce them);
* timestamp wrap, disorder and out-of-range cue tables are written directly
  with :mod:`aircheck.mkvwrite`, because no muxer will emit them on request.

All writers are deterministic: frame content, packet order and metadata depend
only on the parameters, so a fixture can be regenerated byte-for-byte.
"""

from __future__ import annotations

import fractions
import random
from dataclasses import dataclass, field
from pathlib import Path

import av
import numpy as np

from .mkvwrite import (
    MkvBlock,
    MkvCluster,
    MkvCue,
    MkvTrack,
    _encode_cue,
    build_mkv,
    pcm_silence,
)

#: Codec choices per target container.  MOV gets PCM so a lossless remux can
#: preserve raw samples; MP4/MKV get AAC to exercise the compressed path.
FORMAT_PRESETS: dict[str, dict[str, str]] = {
    "mp4": {"format": "mp4", "video": "libx264", "audio": "aac", "extension": "mp4"},
    "mov": {"format": "mov", "video": "mpeg4", "audio": "pcm_s16le", "extension": "mov"},
    "mkv": {"format": "matroska", "video": "libx264", "audio": "aac", "extension": "mkv"},
}

DEFAULT_FPS = 24
DEFAULT_AUDIO_RATE = 48000
DEFAULT_WIDTH = 96
DEFAULT_HEIGHT = 72

#: SILENCE detection threshold used by the audio sampling path (linear scale).
SILENCE_THRESHOLD = 1e-3


@dataclass
class Segment:
    """One timeline segment emitted by a fixture encoder."""

    index: int
    start_ticks: int
    duration_ticks: int
    video_packets: int = 0
    audio_packets: int = 0
    keyframes: int = 0
    applied_transition_ms: int = 0

    def to_dict(self) -> dict[str, object]:
        return {
            "index": self.index,
            "start_ticks": self.start_ticks,
            "duration_ticks": self.duration_ticks,
            "video_packets": self.video_packets,
            "audio_packets": self.audio_packets,
            "keyframes": self.keyframes,
            "applied_transition_ms": self.applied_transition_ms,
        }


@dataclass
class Fixture:
    """A generated input asset plus the facts needed to grade its processing."""

    name: str
    path: Path
    format_key: str
    damage: str | None
    duration_ticks: int
    segment_ticks: int
    segments: list[Segment]
    video_streams: int = 0
    audio_streams: int = 0
    sample_rates: list[int] = field(default_factory=list)
    expected_keyframes: int = 0
    expected_video_packets: int = 0
    expected_audio_packets: int = 0
    note: str = ""

    @property
    def size_bytes(self) -> int:
        return self.path.stat().st_size

    def to_dict(self) -> dict[str, object]:
        return {
            "name": self.name,
            "path": str(self.path),
            "format": self.format_key,
            "damage": self.damage,
            "duration_ticks": self.duration_ticks,
            "segment_ticks": self.segment_ticks,
            "segments": [segment.to_dict() for segment in self.segments],
            "video_streams": self.video_streams,
            "audio_streams": self.audio_streams,
            "sample_rates": list(self.sample_rates),
            "expected_keyframes": self.expected_keyframes,
            "expected_video_packets": self.expected_video_packets,
            "expected_audio_packets": self.expected_audio_packets,
            "size_bytes": self.size_bytes,
            "note": self.note,
        }


# --------------------------------------------------------------------------- #
# Frame synthesis
# --------------------------------------------------------------------------- #

def _video_frame(index: int, width: int, height: int, salt: int) -> av.VideoFrame:
    """A deterministic frame whose luminance encodes its index.

    The coarse block pattern makes GOP boundaries visible while the per-index
    salt guarantees consecutive frames differ, which keeps encoders from
    collapsing them into skip frames.
    """
    yy, xx = np.mgrid[0:height, 0:width]
    base = ((index * 7) + salt * 29) % 256
    array = np.empty((height, width, 3), dtype=np.uint8)
    array[..., 0] = (base + (xx * 3) % 64) % 256
    array[..., 1] = (base + (yy * 5) % 64) % 256
    array[..., 2] = (base * 3 + salt * 11) % 256
    array[::16, :, :] = 255
    array[:, ::16, :] = 0
    return av.VideoFrame.from_ndarray(array, format="rgb24").reformat(format="yuv420p")


def _audio_frame(pts: int, sample_count: int, sample_rate: int, channels: int,
                 amplitude: float, silent: bool) -> av.AudioFrame:
    if silent:
        mono = np.zeros(sample_count, dtype=np.int16)
    else:
        times = np.arange(pts, pts + sample_count)
        wave = np.sin(2 * np.pi * 440.0 * times / sample_rate)
        mono = (wave * amplitude * 32767).astype(np.int16)
    interleaved = np.zeros((1, sample_count * channels), dtype=np.int16)
    for channel in range(channels):
        interleaved[0, channel::channels] = mono
    frame = av.AudioFrame.from_ndarray(interleaved, format="s16", layout="stereo" if channels == 2 else "mono")
    frame.sample_rate = sample_rate
    frame.pts = pts
    frame.time_base = fractions.Fraction(1, sample_rate)
    return frame


