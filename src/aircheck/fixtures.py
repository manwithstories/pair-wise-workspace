@dataclass
class Corpus:
    healthy: list[Fixture] = field(default_factory=list)
    damaged: list[Fixture] = field(default_factory=list)
    spec: EncodeSpec | None = None

    @property
    def all(self) -> list[Fixture]:
        return self.healthy + self.damaged

    def to_dict(self) -> dict[str, object]:
        return {
            "healthy": [fixture.to_dict() for fixture in self.healthy],
            "damaged": [fixture.to_dict() for fixture in self.damaged],
        }


def build_demo_corpus(directory: str | Path, formats: list[str],
                      *, seed: int = 20261120) -> Corpus:
    """Create the multi-format corpus used by ``aircheck demo``.

    Each requested format gets one primary asset (2 video + 2 audio tracks with
    mixed sample rates, 2 s timeline, 500 ms segments) and a wider variant with
    an applied cross-segment transition.  From the primary asset of every format
    a truncated and a corrupted variant are derived.  The timestamp and index
    pathologies are MKV-only and generated once.
    """
    random.seed(seed)
    out_dir = Path(directory)
    out_dir.mkdir(parents=True, exist_ok=True)
    corpus = Corpus()
    for format_key in formats:
        if format_key not in FORMAT_PRESETS:
            raise ValueError(f"unsupported fixture format: {format_key}")
        suffix = "." + FORMAT_PRESETS[format_key]["extension"]
        spec = EncodeSpec(
            format_key=format_key,
            video_streams=2,
            audio_streams=2,
            sample_rates=(48000, 44100),
            duration_ms=2000,
            segment_ms=500,
            gop=12,
        )
        healthy = encode_asset(out_dir / f"normal_{format_key}{suffix}", spec)
        corpus.healthy.append(healthy)
        corpus.damaged.extend(build_damaged_set(healthy, out_dir / "damaged"))
    corpus.damaged.extend(build_index_and_timestamp_set(out_dir / "damaged"))
    corpus.spec = EncodeSpec(format_key=",".join(formats))
    return corpus


