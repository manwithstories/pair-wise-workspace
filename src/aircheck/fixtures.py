def truncate_asset(source: str | Path, target: str | Path, fraction: float) -> Fixture:
    """Copy ``source`` and keep only ``fraction`` of its bytes (tail loss)."""
    if not 0.0 < fraction < 1.0:
        raise ValueError("fraction must be within (0, 1)")
    src = Path(source)
    dst = Path(target)
    dst.parent.mkdir(parents=True, exist_ok=True)
    data = src.read_bytes()
    keep = max(1, int(len(data) * fraction))
    dst.write_bytes(data[:keep])
    return Fixture(
        name=dst.stem,
        path=dst,
        format_key=src.suffix.lstrip("."),
        damage="truncated",
        duration_ticks=0,
        segment_ticks=500_000_000,
        segments=[],
        note=f"kept {keep}/{len(data)} bytes",
    )


def corrupt_asset(source: str | Path, target: str | Path, *, stream_kind: str = "video",
                  packet_index: int = 3, length: int = 96) -> Fixture:
    """Flip bytes inside one compressed packet to simulate transmission damage.

    The packet is located by demuxing ``source`` and its byte offset is taken
    from the container index, so the damage lands inside a real compressed
    payload (flipping raw PCM would remain valid audio and be undetectable).
    """
    src = Path(source)
    dst = Path(target)
    dst.parent.mkdir(parents=True, exist_ok=True)
    offset = _packet_offset(src, stream_kind, packet_index)
    data = bytearray(src.read_bytes())
    stop = min(len(data), offset + length)
    for index in range(offset, stop):
        data[index] ^= 0xA5
    dst.write_bytes(bytes(data))
    return Fixture(
        name=dst.stem,
        path=dst,
        format_key=src.suffix.lstrip("."),
        damage="corrupt",
        duration_ticks=0,
        segment_ticks=500_000_000,
        segments=[],
        note=f"flipped {stop - offset} bytes inside {stream_kind} packet #{packet_index} at {offset}",
    )


def _packet_offset(path: Path, stream_kind: str, packet_index: int) -> int:
    """Return a byte offset inside payload of the Nth packet of ``stream_kind``."""
    container = av.open(str(path))
    try:
        matches = [stream.index for stream in container.streams if stream.type == stream_kind]
        if not matches:
            raise ValueError(f"asset has no {stream_kind} stream to corrupt")
        target_index = matches[0]
        seen = 0
        for packet in container.demux():
            if packet.size == 0 or packet.stream.index != target_index or packet.pos < 0:
                continue
            if seen == packet_index:
                # Skip the container-level frame header that precedes payload.
                return int(packet.pos) + min(packet.size // 2, max(8, packet.size // 3))
            seen += 1
    finally:
        container.close()
    raise ValueError(f"asset has fewer than {packet_index + 1} {stream_kind} packets")


def wrap_timestamp_asset(target: str | Path, *, sample_rate: int = 48000,
                         blocks: int = 40, block_ms: int = 20,
                         wrap_at_ms: int = 400) -> Fixture:
    """Matroska asset whose 32-bit timestamp counter wraps mid-stream.

    Blocks start at ``wrap_at_ms`` and are written so that after a while the
    counter rolls over to zero, which exercises ``TimestampTracker``'s wrap
    classification rather than reporting plain disorder.
    """
    dst = Path(target)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tracks = [MkvTrack(number=1, kind="audio", sample_rate=sample_rate)]
    clusters: list[MkvCluster] = []
    cues: list[MkvCue] = []
    samples_per_block = int(sample_rate * block_ms / 1000)
    payload = pcm_silence(samples_per_block)
    wrap_ticks = 1 << 32
    first = wrap_ticks - wrap_at_ms
    for index in range(blocks):
        absolute = first + index * block_ms
        timecode = absolute % wrap_ticks
        cluster = MkvCluster(timecode_ms=timecode,
                             blocks=[MkvBlock(track=1, timecode_ms=timecode,
                                              keyframe=True, payload=payload)])
        # Cue times must ascend, so they follow presentation order rather than
        # the (wrapping) raw counter; this keeps the wrap fixture's index valid.
        cues.append(MkvCue(track=1, timecode_ms=index * block_ms, cluster_index=index))
        clusters.append(cluster)
    data = build_mkv(tracks, clusters, cues=cues,
                     duration_ms=blocks * block_ms)
    dst.write_bytes(data)
    return Fixture(
        name=dst.stem,
        path=dst,
        format_key="mkv",
        damage="timestamp_wrap",
        duration_ticks=blocks * block_ms * 1_000_000,
        segment_ticks=block_ms * 1_000_000,
        segments=[],
        note=f"timestamps wrap at {wrap_ticks} ms-scale ticks",
    )


def disorder_timestamp_asset(target: str | Path, *, sample_rate: int = 48000,
                             blocks: int = 40, block_ms: int = 20,
                             disorder_at: int = 10) -> Fixture:
    """Matroska asset whose block timecodes move backwards mid-stream."""
    dst = Path(target)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tracks = [MkvTrack(number=1, kind="audio", sample_rate=sample_rate)]
    clusters: list[MkvCluster] = []
    samples_per_block = int(sample_rate * block_ms / 1000)
    payload = pcm_silence(samples_per_block)
    timecodes = [index * block_ms for index in range(blocks)]
    # Step back by five blocks once, then continue forward from the old peak.
    if 0 <= disorder_at < blocks:
        timecodes[disorder_at] = max(0, (disorder_at - 5) * block_ms)
    for index, timecode in enumerate(timecodes):
        cluster = MkvCluster(timecode_ms=timecode,
                             blocks=[MkvBlock(track=1, timecode_ms=timecode,
                                              keyframe=True, payload=payload)])
        clusters.append(cluster)
    # Cues are ordered by cluster, not by timecode, so the file stays seekable
    # and the disorder is purely in block timestamps.
    cues = [MkvCue(track=1, timecode_ms=index * block_ms, cluster_index=index)
            for index in range(blocks)]
    data = build_mkv(tracks, clusters, cues=cues, duration_ms=blocks * block_ms)
    dst.write_bytes(data)
    return Fixture(
        name=dst.stem,
        path=dst,
        format_key="mkv",
        damage="timestamp_disorder",
        duration_ticks=blocks * block_ms * 1_000_000,
        segment_ticks=block_ms * 1_000_000,
        segments=[],
        note=f"block #{disorder_at} steps backwards",
    )


def bad_index_asset(target: str | Path, *, sample_rate: int = 48000,
                    blocks: int = 40, block_ms: int = 20) -> Fixture:
    """Matroska asset whose Cues table is structurally broken.

    Cue entries are duplicated, written out of order and one offset points past
    EOF, so an index checker can detect duplicate, mis-ordered and
    out-of-range entries in a single asset.
    """
    dst = Path(target)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tracks = [MkvTrack(number=1, kind="audio", sample_rate=sample_rate)]
    clusters: list[MkvCluster] = []
    samples_per_block = int(sample_rate * block_ms / 1000)
    payload = pcm_silence(samples_per_block)
    for index in range(blocks):
        timecode = index * block_ms
        clusters.append(MkvCluster(timecode_ms=timecode,
                                   blocks=[MkvBlock(track=1, timecode_ms=timecode,
                                                    keyframe=True, payload=payload)]))
    # Cue points are emitted in this deliberately wrong order (the ``cue_time``
    # key is only documentation; Cues are supposed to be ascending by time):
    #   time 0     cluster 0   (correct, but duplicated immediately after)
    #   time 0     cluster 0   duplicate entry
    #   time 780   cluster 39  correct near-tail entry
    #   time 100   cluster 10  written after 780 -> out of order
    #   time 60    cluster 1   offset 10**9 bytes -> past EOF
    duplicate = MkvCue(track=1, timecode_ms=0, cluster_index=0)
    past_eof = MkvCue(track=1, timecode_ms=block_ms * 3, cluster_index=1)
    cue_points: list[bytes] = [
        _encode_cue(duplicate, 0),
        _encode_cue(duplicate, 0),
        _encode_cue(MkvCue(track=1, timecode_ms=blocks * block_ms - block_ms,
                           cluster_index=blocks - 1), 0),
        _encode_cue(MkvCue(track=1, timecode_ms=block_ms * 5, cluster_index=10), 0),
        # CueClusterPosition is an offset into the Segment body; 10**9 lands
        # far beyond this file's ~150 KiB, which is the out-of-range case.
        _encode_cue(past_eof, 10 ** 9),
    ]
    cues_blob = b"".join(cue_points)
    data = build_mkv(tracks, clusters, cues_blob=cues_blob,
                     duration_ms=blocks * block_ms)
    dst.write_bytes(data)
    return Fixture(
        name=dst.stem,
        path=dst,
        format_key="mkv",
        damage="bad_index",
        duration_ticks=blocks * block_ms * 1_000_000,
        segment_ticks=block_ms * 1_000_000,
        segments=[],
        note="cues contain duplicate, disordered and past-EOF entries",
    )


def _variant_path(directory: Path, base: str, suffix: str, label: str) -> Path:
    return directory / f"{base}_{label}{suffix}"


def build_damaged_set(source: Fixture, directory: str | Path) -> list[Fixture]:
    """Derive truncation/corruption fixtures from a healthy asset."""
    out_dir = Path(directory)
    out_dir.mkdir(parents=True, exist_ok=True)
    suffix = source.path.suffix
    name = source.path.stem
    fixtures = [
        truncate_asset(source.path, _variant_path(out_dir, name, suffix, "trunc"), 0.6),
        corrupt_asset(source.path, _variant_path(out_dir, name, suffix, "corrupt")),
    ]
    return fixtures


def build_index_and_timestamp_set(directory: str | Path) -> list[Fixture]:
    out_dir = Path(directory)
    out_dir.mkdir(parents=True, exist_ok=True)
    return [
        wrap_timestamp_asset(out_dir / "damaged_wrap.mkv"),
        disorder_timestamp_asset(out_dir / "damaged_disorder.mkv"),
        bad_index_asset(out_dir / "damaged_bad_index.mkv"),
    ]


