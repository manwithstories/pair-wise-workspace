@dataclass
class EncodeSpec:
    format_key: str
    video_streams: int = 1
    audio_streams: int = 2
    sample_rates: tuple[int, ...] = (48000, 44100)
    duration_ms: int = 2000
    segment_ms: int = 500
    fps: int = DEFAULT_FPS
    gop: int = 12
    transition_ms: int = 0
    audio_chunk: int = 1024
    silent_audio: bool = False


def _encode_asset(path: Path, spec: EncodeSpec) -> dict[str, object]:
    preset = FORMAT_PRESETS[spec.format_key]
    options: dict[str, str] = {}
    if preset["format"] in ("mov", "mp4"):
        # Write the index up front so a truncated tail stays openable; this is
        # also what a mastering house would receive from a fast-start export.
        options["movflags"] = "+faststart"
    container = av.open(str(path), "w", format=preset["format"], options=options)
    try:
        frame_count = max(1, int(spec.duration_ms * spec.fps / 1000))
        video_streams = []
        for offset in range(spec.video_streams):
            stream = container.add_stream(preset["video"], rate=spec.fps)
            stream.width = DEFAULT_WIDTH + offset * 16
            stream.height = DEFAULT_HEIGHT
            stream.pix_fmt = "yuv420p"
            if preset["video"] == "libx264":
                stream.options = {
                    "preset": "ultrafast",
                    "g": str(spec.gop),
                    "keyint_min": str(spec.gop),
                    "sc_threshold": "0",
                    "bf": "0",
                }
            video_streams.append(stream)

        audio_streams = []
        rates = list(spec.sample_rates)
        for offset in range(spec.audio_streams):
            rate = rates[offset % len(rates)]
            stream = container.add_stream(preset["audio"], rate=rate)
            stream.layout = "stereo"
            audio_streams.append((rate, stream))

        keyframes = 0
        for index in range(frame_count):
            for offset, stream in enumerate(video_streams):
                frame = _video_frame(index, stream.width, stream.height, offset)
                frame.pts = index
                frame.time_base = fractions.Fraction(1, spec.fps)
                for packet in stream.encode(frame):
                    if packet.is_keyframe:
                        keyframes += 1
                    container.mux(packet)
        for stream in video_streams:
            for packet in stream.encode(None):
                if packet.is_keyframe:
                    keyframes += 1
                container.mux(packet)

        for rate, stream in audio_streams:
            total = int(spec.duration_ms * rate / 1000)
            pts = 0
            while pts < total:
                count = min(spec.audio_chunk, total - pts)
                silent = spec.silent_audio and (pts // rate) % 2 == 1
                frame = _audio_frame(pts, count, rate, 2, 0.25, silent)
                for packet in stream.encode(frame):
                    container.mux(packet)
                pts += count
        for _, stream in audio_streams:
            for packet in stream.encode(None):
                container.mux(packet)
    finally:
        container.close()

    segment_ticks = spec.segment_ms * 1_000_000
    duration_ticks = spec.duration_ms * 1_000_000
    segments = []
    segment_count = max(1, (duration_ticks + segment_ticks - 1) // segment_ticks)
    for index in range(segment_count):
        start = index * segment_ticks
        length = min(segment_ticks, duration_ticks - start)
        transition = spec.transition_ms if 0 < index < segment_count - 1 else 0
        segments.append(
            Segment(
                index=index,
                start_ticks=start,
                duration_ticks=length,
                applied_transition_ms=transition,
            )
        )
    return {
        "duration_ticks": duration_ticks,
        "segment_ticks": segment_ticks,
        "segments": segments,
        "keyframes": keyframes,
        "video_streams": len(video_streams),
        "audio_streams": len(audio_streams),
        "sample_rates": [rate for rate, _ in audio_streams],
        "total_video_packets": frame_count * len(video_streams),
    }


def encode_asset(path: str | Path, spec: EncodeSpec) -> Fixture:
    """Encode a healthy multi-track asset and return its grading facts."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    facts = _encode_asset(target, spec)
    return Fixture(
        name=target.stem,
        path=target,
        format_key=spec.format_key,
        damage=None,
        duration_ticks=facts["duration_ticks"],
        segment_ticks=facts["segment_ticks"],
        segments=facts["segments"],
        video_streams=facts["video_streams"],
        audio_streams=facts["audio_streams"],
        sample_rates=facts["sample_rates"],
        expected_keyframes=facts["keyframes"],
        expected_video_packets=facts["total_video_packets"],
    )


