"""Command-line interface: repair command with JSON output.

Exit codes:
    0 - success (all data recovered, all seek verifications passed)
    1 - unrecovered data remains or index seek verification failed
    2 - unreadable input or invalid arguments
"""

from __future__ import annotations

import argparse
import json
import sys

from .errors import InputError, UnrecoveredDataError
from .pipeline import run


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="remuxsync",
        description="Repair, align and re-index multi-track raw media streams.")
    sub = parser.add_subparsers(dest="command", required=True)

    repair = sub.add_parser("repair", help="repair a sample directory")
    repair.add_argument("--input", required=True,
                        help="input directory generated by make_samples.py")
    repair.add_argument("--output", required=True,
                        help="output directory (must not be inside --input)")
    repair.add_argument("--reorder-window-ms", type=int, default=120,
                        help="bounded per-track reorder buffer window (ms)")
    repair.add_argument("--json", action="store_true",
                        help="emit the full report as JSON on stdout")
    return parser


def _report(result, output_dir: str) -> dict:
    summary = dict(result.summary)
    summary["output_dir"] = output_dir
    summary["errors"] = result.errors.to_list()
    summary["error_count"] = len(result.errors.records)
    summary["unrecovered_count"] = len(result.errors.unrecovered)
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    if args.command != "repair":  # pragma: no cover - argparse enforces this
        parser.error("unknown command")
    try:
        result = run(args.input, args.output, args.reorder_window_ms)
    except InputError as exc:
        if args.json:
            print(json.dumps({"status": "error", "error": str(exc)}))
        else:
            print(f"error: {exc}", file=sys.stderr)
        return 2
    except UnrecoveredDataError as exc:  # defensive; run() records instead
        print(f"error: {exc}", file=sys.stderr)
        return 1

    report = _report(result, args.output)
    if args.json:
        print(json.dumps(report, indent=2, ensure_ascii=False))
    else:
        for key in ("sync_error_ms_p95", "packet_recovery_rate",
                    "latency_ms_p95", "index_seek_failures"):
            print(f"{key}: {report[key]}")
        print(f"errors: {report['error_count']} "
              f"(unrecovered: {report['unrecovered_count']})")

    has_unrecovered = bool(result.errors.unrecovered)
    if has_unrecovered or result.seek_failures:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
