Image make_fixture_image() {
  Image image;
  image.width = kFixtureWidth;
  image.height = kFixtureHeight;
  image.rgb.resize(image.pixel_count() * 3);

  const int half_h = kFixtureHeight / 2;
  const int half_w = kFixtureWidth / 2;
  for (int y = 0; y < kFixtureHeight; ++y) {
    for (int x = 0; x < kFixtureWidth; ++x) {
      const std::size_t p = static_cast<std::size_t>(y) * kFixtureWidth + x;
      std::uint8_t r = 0;
      std::uint8_t g = 0;
      std::uint8_t b = 0;
      if (y < half_h) {
        // Gradient: red tracks x, green tracks y, blue is a fixed mid value.
        r = clamp_byte(static_cast<long>(x) * 255 / (kFixtureWidth - 1));
        g = clamp_byte(static_cast<long>(y) * 255 / (half_h - 1));
        b = 128;
      } else if (x < half_w) {
        // Checkerboard: alternating mid/high values to stress quantization.
        const bool on = ((x / 4) + (y / 4)) % 2 == 0;
        r = on ? 220 : 35;
        g = on ? 35 : 220;
        b = on ? 200 : 60;
      } else {
        // Highlight block: near-white values in a small step ladder.
        const long level = 235 + (x - half_w) % 3 * 7;
        r = clamp_byte(level);
        g = clamp_byte(level - 3);
        b = clamp_byte(level - 6);
      }
      image.rgb[p * 3 + 0] = r;
      image.rgb[p * 3 + 1] = g;
      image.rgb[p * 3 + 2] = b;
    }
  }
  return image;
}

std::string make_demo_cube(int grid_size, const std::string& title) {
  if (grid_size < 2) {
    throw Error(ExitCode::kUsage, "fixture_invalid", "grid size must be >= 2");
  }
  std::ostringstream out;
  out << "TITLE \"" << title << "\"\n";
  out << "# generated by lutgrade generate-fixture (deterministic)\n";
  out << "LUT_3D_SIZE " << grid_size << "\n";
  out << "DOMAIN_MIN 0.0 0.0 0.0\n";
  out << "DOMAIN_MAX 1.0 1.0 1.0\n";

  const double denom = static_cast<double>(grid_size - 1);
  auto fmt = [](double v) {
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%.6f", v);
    return std::string(buf);
  };
  for (int b = 0; b < grid_size; ++b) {
    for (int g = 0; g < grid_size; ++g) {
      for (int r = 0; r < grid_size; ++r) {
        // The S-curve is monotonic and stays within [0,1] on [0,1], but clamp
        // defensively so the emitted file always parses.
        const double vr = std::fmin(1.0, std::fmax(0.0, demo_curve(r / denom)));
        const double vg = std::fmin(1.0, std::fmax(0.0, demo_curve(g / denom)));
        const double vb = std::fmin(1.0, std::fmax(0.0, demo_curve(b / denom)));
        out << fmt(vr) << ' ' << fmt(vg) << ' ' << fmt(vb) << '\n';
      }
    }
  }
  return out.str();
}

void generate_fixtures(const std::string& dir, int grid_size) {
  if (grid_size != 17 && grid_size != 33 && grid_size != 65) {
    throw Error(ExitCode::kUsage, "fixture_invalid",
                "grid size must be 17, 33 or 65");
  }
  ensure_dir(dir);
  const std::string base = dir.empty() ? "" : dir + "/";

  write_ppm(base + "input.ppm", make_fixture_image());

  const int sizes[3] = {17, 33, 65};
  for (const int n : sizes) {
    const std::string name =
        n == grid_size ? "demo.cube" : "lut" + std::to_string(n) + ".cube";
    const std::string title =
        n == grid_size ? "lutgrade demo" : "lutgrade demo " + std::to_string(n);
    std::ofstream out(base + name, std::ios::binary | std::ios::trunc);
    if (!out) {
      throw Error(ExitCode::kUsage, "fixture_io",
                  "cannot write fixture: " + base + name);
    }
    out << make_demo_cube(n, title);
    out.flush();
    if (!out) {
      throw Error(ExitCode::kUsage, "fixture_io",
                  "failed writing fixture: " + base + name);
    }
  }
}

