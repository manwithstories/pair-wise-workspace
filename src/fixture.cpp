// Smooth, odd-symmetric S-curve around 0.5. Kept monotonic in [0,1]: its
// derivative is 1 + amp*(2 - 12x + 12x^2), whose minimum is 1 - amp at x=0.5.
double demo_curve(double x) {
  return x + kDemoCurveAmplitude * (x * (1.0 - x) * (2.0 * x - 1.0));
}

std::uint8_t clamp_byte(long v) {
  if (v < 0) return 0;
  if (v > 255) return 255;
  return static_cast<std::uint8_t>(v);
}

void ensure_dir(const std::string& dir) {
  if (dir.empty()) return;
  // mkdir -p equivalent without <filesystem> to keep the code C++17-portable
  // across old libstdc++ builds.
  std::string built;
  for (std::size_t i = 0; i <= dir.size(); ++i) {
    if (i == dir.size() || dir[i] == '/') {
      if (!built.empty() && built != "." && built != "..") {
        if (::mkdir(built.c_str(), 0777) != 0 && errno != EEXIST) {
          throw Error(ExitCode::kUsage, "fixture_io",
                      "cannot create directory: " + built);
        }
      }
    }
    if (i < dir.size()) built.push_back(dir[i]);
  }
}

